/**
 * Reasonix CLI 辅助（对标 grok-config.ts）。
 *
 * Reasonix 是 DeepSeek 原生终端 coding agent（npm i -g reasonix）。
 * ccjk 只做：探测安装/配置、生成启动建议、从 ~/.ccjk/config.toml profile 注入 env 启动。
 * 不把 key 写入 reasonix.toml（Reasonix 用 api_key_env 指向环境变量）。
 */

import { execSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'pathe'
import ansis from 'ansis'

export const REASONIX_GLOBAL_CONFIG = join(homedir(), '.config', 'reasonix', 'config.toml')
export const REASONIX_PROJECT_CONFIG = 'reasonix.toml'

export interface CcjkReasonixProfile {
  name?: string
  baseUrl?: string
  apiKey?: string
  model?: string
  provider?: string
}

export interface ReasonixLaunchOptions {
  model?: string
  prompt?: string
}

export interface ReasonixEnvMapping {
  envKey: string
  providerName: string
  baseUrl: string
  model: string
}

const DEEPSEEK_OPENAI_BASE = 'https://api.deepseek.com'

const MODEL_ALIASES: Record<string, string> = {
  'deepseek-chat': 'deepseek-v4-flash',
  'deepseek-reasoner': 'deepseek-v4-pro',
  'deepseek-coder': 'deepseek-v4-flash',
}

/** reasonix 命令是否在 PATH 上。 */
export function isReasonixInstalled(): boolean {
  try {
    execSync('command -v reasonix', { stdio: 'ignore' })
    return true
  }
  catch {
    return false
  }
}

export function resolveReasonixConfigPath(cwd = process.cwd()): string | null {
  const projectPath = join(cwd, REASONIX_PROJECT_CONFIG)
  if (existsSync(projectPath)) return projectPath
  if (existsSync(REASONIX_GLOBAL_CONFIG)) return REASONIX_GLOBAL_CONFIG
  return null
}

export function hasReasonixConfig(cwd = process.cwd()): boolean {
  return resolveReasonixConfigPath(cwd) !== null
}

function normalizeOpenAiBaseUrl(baseUrl?: string): string {
  if (!baseUrl?.trim()) return DEEPSEEK_OPENAI_BASE
  const trimmed = baseUrl.trim().replace(/\/+$/, '')
  if (trimmed.includes('deepseek.com')) {
    return trimmed
      .replace(/\/anthropic$/i, '')
      .replace(/\/v1$/i, '')
      || DEEPSEEK_OPENAI_BASE
  }
  if (trimmed.includes('xiaomimimo.com')) {
    return trimmed.endsWith('/v1') ? trimmed : `${trimmed}/v1`
  }
  return trimmed
}

function inferEnvMapping(profile: CcjkReasonixProfile): ReasonixEnvMapping {
  const baseUrl = normalizeOpenAiBaseUrl(profile.baseUrl)
  const rawModel = profile.model?.trim() || 'deepseek-v4-flash'
  const model = MODEL_ALIASES[rawModel] || rawModel

  if (baseUrl.includes('xiaomimimo.com')) {
    return {
      envKey: 'MIMO_API_KEY',
      providerName: 'mimo-pro',
      baseUrl,
      model: model.startsWith('mimo-') ? model : 'mimo-v2.5-pro',
    }
  }

  return {
    envKey: 'DEEPSEEK_API_KEY',
    providerName: 'deepseek',
    baseUrl,
    model,
  }
}

/** 从 ccjk profile 推导 Reasonix 运行时环境变量（不写盘）。 */
export function mapProfileToReasonixEnv(profile: CcjkReasonixProfile): Record<string, string> {
  const mapping = inferEnvMapping(profile)
  const env: Record<string, string> = {}
  if (profile.apiKey) {
    env[mapping.envKey] = profile.apiKey
  }
  return env
}

export function getReasonixProfileMapping(profile: CcjkReasonixProfile): ReasonixEnvMapping {
  return inferEnvMapping(profile)
}

export function buildReasonixTomlFromProfile(profile: CcjkReasonixProfile): string {
  const mapping = inferEnvMapping(profile)
  const models = [mapping.model]
  return [
    `# Generated by ccjk — secrets via ${mapping.envKey}, never put keys here.`,
    `default_model = "${mapping.providerName}"`,
    '',
    '[[providers]]',
    `name        = "${mapping.providerName}"`,
    'kind        = "openai"',
    `base_url    = "${mapping.baseUrl}"`,
    `models      = ${JSON.stringify(models)}`,
    `default     = "${mapping.model}"`,
    `api_key_env = "${mapping.envKey}"`,
    '',
  ].join('\n')
}

/**
 * 若项目根尚无 reasonix.toml，从 profile 生成最小配置（有则跳过，避免覆盖用户定制）。
 */
export function ensureReasonixProjectConfig(
  profile: CcjkReasonixProfile,
  cwd = process.cwd(),
): { written: boolean; path: string; backup: string | null } {
  const path = join(cwd, REASONIX_PROJECT_CONFIG)
  if (existsSync(path)) {
    return { written: false, path, backup: null }
  }
  writeFileSync(path, buildReasonixTomlFromProfile(profile), 'utf-8')
  return { written: true, path, backup: null }
}

export function suggestReasonixLaunch(opts: ReasonixLaunchOptions = {}): string {
  const parts = ['reasonix']
  if (opts.model) parts.push('run', '--model', opts.model)
  else parts.push('chat')
  if (opts.prompt) {
    parts.length = 1
    parts.push('run', opts.prompt.includes(' ') ? `"${opts.prompt}"` : opts.prompt)
    if (opts.model) parts.splice(2, 0, '--model', opts.model)
  }
  return parts.join(' ')
}

export function getReasonixQuickStatus(cwd = process.cwd()): {
  installed: boolean
  hasConfig: boolean
  configPath: string | null
  hasDeepSeekKey: boolean
  hasMimoKey: boolean
  hint: string
} {
  const installed = isReasonixInstalled()
  const configPath = resolveReasonixConfigPath(cwd)
  const hasConfig = configPath !== null
  const hasDeepSeekKey = Boolean(process.env.DEEPSEEK_API_KEY?.trim())
  const hasMimoKey = Boolean(process.env.MIMO_API_KEY?.trim())

  if (!installed) {
    return {
      installed: false,
      hasConfig,
      configPath,
      hasDeepSeekKey,
      hasMimoKey,
      hint: '未安装：npm i -g reasonix',
    }
  }
  if (!hasConfig) {
    return {
      installed: true,
      hasConfig: false,
      configPath: null,
      hasDeepSeekKey,
      hasMimoKey,
      hint: hasDeepSeekKey || hasMimoKey
        ? '已安装，建议运行 reasonix setup 或 ccjk reasonix <profile> 生成 reasonix.toml'
        : '已安装，运行 reasonix setup 或设置 DEEPSEEK_API_KEY',
    }
  }
  if (!hasDeepSeekKey && !hasMimoKey) {
    return {
      installed: true,
      hasConfig: true,
      configPath,
      hasDeepSeekKey: false,
      hasMimoKey: false,
      hint: `已安装且找到配置（${configPath}），但环境变量中无 API key`,
    }
  }
  return {
    installed: true,
    hasConfig: true,
    configPath,
    hasDeepSeekKey,
    hasMimoKey,
    hint: '已就绪，可 reasonix chat 或 reasonix run',
  }
}

export function buildReasonixHints(cwd = process.cwd()): string[] {
  const status = getReasonixQuickStatus(cwd)
  const lines: string[] = []

  if (!status.installed) {
    lines.push(ansis.yellow('\nReasonix 未安装'))
    lines.push(ansis.dim('  安装: ') + ansis.cyan('npm i -g reasonix'))
    lines.push(ansis.dim('  说明: ') + ansis.gray('DeepSeek 原生终端 coding agent，长会话前缀缓存降本'))
    return lines
  }

  lines.push(ansis.bold('\nReasonix CLI'))
  lines.push(
    `  安装: ${ansis.green('是')}`
    + `  配置: ${status.hasConfig ? ansis.green('是') : ansis.yellow('否')}`
    + `  API Key: ${(status.hasDeepSeekKey || status.hasMimoKey) ? ansis.green('是') : ansis.yellow('否')}`,
  )
  if (status.configPath) {
    lines.push(ansis.dim(`  配置路径: ${status.configPath}`))
  }

  if (!status.hasConfig) {
    lines.push(ansis.dim('  初始化: ') + ansis.cyan('reasonix setup'))
    lines.push(ansis.dim('  或: ') + ansis.cyan('ccjk reasonix <profile>') + ansis.dim('（从 ccjk profile 注入 key 并生成 reasonix.toml）'))
  }

  if (!status.hasDeepSeekKey && !status.hasMimoKey) {
    lines.push(ansis.dim('  密钥: ') + ansis.cyan('export DEEPSEEK_API_KEY=sk-...'))
  }

  lines.push(ansis.bold('  常用命令:'))
  lines.push(`    ${ansis.cyan('reasonix chat')}           ${ansis.dim('交互式 TUI（项目内 /init 生成 AGENTS.md）')}`)
  lines.push(`    ${ansis.cyan('reasonix run "<task>"')}  ${ansis.dim('单次自主执行任务')}`)
  lines.push(`    ${ansis.cyan('reasonix setup')}          ${ansis.dim('配置向导 → reasonix.toml')}`)

  lines.push(ansis.dim('\n  DeepSeek 两条路径:'))
  lines.push(ansis.dim('    Claude 协议 → ccjk + Clavue/Claude Code（Anthropic 兼容网关）'))
  lines.push(ansis.dim('    OpenAI 协议 → Reasonix（DeepSeek 原生 agent + 前缀缓存）'))

  return lines
}

/** 读取 reasonix.toml 中的 default_model（尽力解析，失败返回 null）。 */
export function readReasonixDefaultModel(configPath: string): string | null {
  if (!existsSync(configPath)) return null
  try {
    const content = readFileSync(configPath, 'utf-8')
    const match = content.match(/^default_model\s*=\s*["']?([^"'\n#]+)["']?/m)
    return match?.[1]?.trim() || null
  }
  catch {
    return null
  }
}